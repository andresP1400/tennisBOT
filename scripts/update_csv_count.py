"""One-shot utility: append totalMatches / testMatches rows to an existing
metrics_summary.csv generated by the training pipeline.

Use only if those rows are missing because of an older evaluation.py that
didn't include them.
"""

from __future__ import annotations

import os

import pandas as pd

PATH = "reports/atp/metrics_summary.csv"


def main() -> None:
    if not os.path.exists(PATH):
        print("Not found")
        return
    df = pd.read_csv(PATH)
    if "totalMatches" not in df["metric"].values:
        new_rows = pd.DataFrame(
            {
                "metric": ["totalMatches", "testMatches"],
                "test": [144558, 2973],
                "val": [144558, 2973],
            }
        )
        df = pd.concat([df, new_rows], ignore_index=True)
        df.to_csv(PATH, index=False)
        print("Updated metrics_summary.csv")
    else:
        print("Already has totalMatches row")


if __name__ == "__main__":
    main()
