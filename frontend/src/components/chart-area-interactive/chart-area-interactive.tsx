"use client"

import { useEffect, useState } from "react"
import { IconPhoto } from "@tabler/icons-react"
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card"
import { Button } from "@/components/ui/button"
import { API_DISPLAY_URL } from "@/lib/api"
import { getCharts } from "@/services/analytics"
import type { ChartInfo } from "@/types/api"

export function ChartAreaInteractive() {
  const [charts, setCharts] = useState<ChartInfo[]>([])
  const [tour, setTour] = useState<"atp" | "wta">("atp")
  const [activeChart, setActiveChart] = useState<string>("")
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    const controller = new AbortController()
    const load = async () => {
      try {
        const data = await getCharts(tour, controller.signal)
        const available = (data.charts ?? []).filter((c) => c.exists)
        setCharts(available)
        setError(null)
        if (available.length > 0) {
          setActiveChart(available[0].file)
        } else {
          setActiveChart("")
        }
      } catch (err) {
        if (err instanceof DOMException && err.name === "AbortError") return
        setError(err instanceof Error ? err.message : "Failed to load charts")
        setCharts([])
        setActiveChart("")
      }
    }
    void load()
    return () => controller.abort()
  }, [tour])

  return (
    <Card>
      <CardHeader className="flex flex-col items-stretch space-y-0 border-b p-0 sm:flex-row">
        <div className="flex flex-1 flex-col justify-center gap-1 px-6 py-5 sm:py-6">
          <CardTitle>Model Analysis Plots</CardTitle>
          <CardDescription>
            Showing evaluation reports generated by the Python pipeline.
            Source: <span className="font-mono text-xs">{API_DISPLAY_URL}</span>
          </CardDescription>
        </div>
        <div className="flex items-center gap-2 px-6 py-4 sm:py-6">
          <select
            value={tour}
            onChange={(e) => setTour(e.target.value as "atp" | "wta")}
            className="h-8 rounded-md border border-input bg-background px-2 text-xs"
          >
            <option value="atp">ATP</option>
            <option value="wta">WTA</option>
          </select>
          {charts.map((chart) => (
            <Button
              key={chart.file}
              variant={activeChart === chart.file ? "default" : "outline"}
              size="sm"
              onClick={() => setActiveChart(chart.file)}
            >
              {chart.name}
            </Button>
          ))}
        </div>
      </CardHeader>
      <CardContent className="px-2 pt-4 sm:px-6 sm:pt-6">
        {error && (
          <p className="text-sm text-red-400 mb-4">Backend error: {error}</p>
        )}
        <div className="aspect-[16/9] w-full relative flex items-center justify-center bg-muted/20 overflow-hidden rounded-md border border-neutral-800">
          {activeChart ? (
            // Using <img> rather than next/image because the chart route
            // is a sanitized dynamic PNG endpoint; next/image cannot
            // optimize arbitrary user-supplied filenames.
            // eslint-disable-next-line @next/next/no-img-element
            <img
              src={`/api/charts/${activeChart}?tour=${tour}`}
              alt="Analysis chart"
              className="object-contain w-full h-full"
            />
          ) : (
            <div className="flex flex-col items-center justify-center text-muted-foreground">
              <IconPhoto className="h-10 w-10 mb-2 opacity-50" />
              <p>No charts available</p>
              <p className="text-xs opacity-70">
                Run <span className="font-mono">python main.py train --tour {tour}</span>{" "}
                to generate reports.
              </p>
            </div>
          )}
        </div>
      </CardContent>
    </Card>
  )
}
